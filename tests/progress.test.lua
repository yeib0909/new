local Progress = require("../src/ReplicatedStorage/Progress")
local Lease = require("../src/ReplicatedStorage/ProfileLease")
local d = {coins = 0, xp = 0, rounds = 0, wins = 0, dailyDay = 0, dailyRounds = 0, dailyClaimed = false, missionClaimed = false}
local t = 86400 * 123
assert(Progress.claimDaily(d, t, 75))
assert(not Progress.claimDaily(d, t + 20, 75) and d.coins == 75)
assert(not Progress.claimMission(d, t, 3, 175))
Progress.finishRound(d, true, t)
Progress.finishRound(d, false, t)
Progress.finishRound(d, true, t)
assert(d.rounds == 3 and d.wins == 2 and d.xp == 90 and d.dailyRounds == 3)
assert(Progress.claimMission(d, t, 3, 175) and d.coins == 250)
assert(not Progress.claimMission(d, t, 3, 175))
assert(Progress.claimDaily(d, t + 86400, 75))
assert(d.dailyRounds == 0 and d.missionClaimed == false and d.coins == 325)
assert(Progress.level(0) == 1 and Progress.level(99) == 1 and Progress.level(100) == 2 and Progress.level(400) == 5)
local old = {coins = 40, skin = "Solar"}
local a = Lease.acquire(old, "a", 100)
assert(a.coins == 40 and old._lease == nil and a._lease.id == "a")
assert(Lease.acquire(a, "b", 279) == nil)
local renewed = Lease.save(a, {coins = 80}, "a", 150, false)
assert(renewed.coins == 80 and renewed._lease.expires == 330)
assert(Lease.save(renewed, {coins = 999}, "b", 151, false) == nil)
assert(Lease.release(renewed, "b") == nil)
local takeover = Lease.acquire(renewed, "b", 330)
assert(takeover._lease.id == "b")
assert(Lease.save(takeover, {coins = 100}, "a", 331, true) == nil)
local final = Lease.save(takeover, {coins = 90}, "b", 331, true)
assert(final.coins == 90 and final._lease == nil)
print("Daily progression and profile lease rules passed")
